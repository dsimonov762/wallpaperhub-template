-- media-service schema (README 6.2, pipeline in README 10). PostgreSQL 14+ (bit_count on bit strings needs 14).
-- Same conventions as the account schema: timestamptz, CHECK constraints, application-managed version/updated_at.

CREATE TABLE media_asset (
    id             text        PRIMARY KEY,                             -- 'ast_' + ULID, generated by the service
    owner_id       uuid        NOT NULL,                                -- Keycloak sub; no FK across services
    purpose        text        NOT NULL,
    status         text        NOT NULL DEFAULT 'PROCESSING',
    original_key   text        NOT NULL,                                -- private object key of the untouched upload
    content_type   text        NOT NULL,                                -- decided from magic bytes, never from the client
    size_bytes     bigint      NOT NULL,
    width          integer,                                             -- of the normalized full image; set when READY
    height         integer,
    sha256         text,                                                -- hex digest of the original, exact-duplicate detection
    phash          bit(64),                                             -- perceptual hash, near-duplicate detection
    blurhash       text,
    palette        jsonb       NOT NULL DEFAULT '[]'::jsonb,            -- ["#2b3a2f", ...]
    reject_reason  text,                                                -- reason code when REJECTED
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    version        bigint      NOT NULL DEFAULT 0,

    CONSTRAINT media_asset_id_format      CHECK (id ~ '^ast_[0-9A-HJKMNP-TV-Z]{26}$'),
    CONSTRAINT media_asset_purpose_values CHECK (purpose IN ('AVATAR', 'BANNER', 'WALLPAPER')),
    CONSTRAINT media_asset_status_values  CHECK (status IN ('PROCESSING', 'READY', 'REJECTED')),
    CONSTRAINT media_asset_content_type    CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/avif')),
    CONSTRAINT media_asset_size_positive  CHECK (size_bytes > 0),
    CONSTRAINT media_asset_dims_positive  CHECK ((width IS NULL OR width > 0) AND (height IS NULL OR height > 0)),
    CONSTRAINT media_asset_sha256_format  CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT media_asset_palette_array  CHECK (jsonb_typeof(palette) = 'array'),
    CONSTRAINT media_asset_reason_format  CHECK (reject_reason IS NULL OR reject_reason ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT media_asset_version_nonneg CHECK (version >= 0),
    -- State machine: a READY asset is complete, a REJECTED one says why, everything else has neither.
    CONSTRAINT media_asset_ready_complete CHECK (status <> 'READY' OR (width IS NOT NULL AND height IS NOT NULL AND sha256 IS NOT NULL)),
    CONSTRAINT media_asset_reason_iff_rejected CHECK ((status = 'REJECTED') = (reject_reason IS NOT NULL))
);

CREATE UNIQUE INDEX media_asset_original_key_uq ON media_asset (original_key);
-- GET /media: the caller's assets, newest first, optional purpose/status filters.
CREATE INDEX media_asset_owner_idx   ON media_asset (owner_id, created_at DESC, id);
-- Exact duplicates.
CREATE INDEX media_asset_sha256_idx  ON media_asset (sha256) WHERE sha256 IS NOT NULL;
-- Hourly orphan cleanup looks at assets that never left PROCESSING.
CREATE INDEX media_asset_stuck_idx   ON media_asset (created_at) WHERE status = 'PROCESSING';

COMMENT ON TABLE  media_asset IS 'An uploaded image and the result of processing it. Variants live in media_variant.';
COMMENT ON COLUMN media_asset.phash IS 'Near-duplicate check without extensions: bit_count(phash # $1) <= 6 (Hamming distance). It is a scan, which is fine at reference-project scale; use a BK-tree or a vector index beyond that.';
COMMENT ON COLUMN media_asset.reject_reason IS 'UNSUPPORTED_FORMAT, TOO_SMALL, TOO_LARGE_PIXELS, DUPLICATE, MODERATION, ... (media.reject-reason.<CODE> in contracts/i18n).';
COMMENT ON COLUMN media_asset.version IS 'Optimistic lock counter.';

-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE media_variant (
    id          bigint  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    asset_id    text    NOT NULL REFERENCES media_asset (id) ON DELETE CASCADE,
    kind        text    NOT NULL,       -- WALLPAPER: FULL, PREVIEW, THUMBNAIL. AVATAR: AVATAR_512, AVATAR_128, AVATAR_48. BANNER: BANNER_1500, BANNER_750
    key         text    NOT NULL,       -- '{purpose}/{yyyy}/{mm}/{assetId}/{variant}.{ext}' in the public bucket
    width       integer NOT NULL,
    height      integer NOT NULL,
    format      text    NOT NULL,
    size_bytes  bigint  NOT NULL,

    CONSTRAINT media_variant_kind_format   CHECK (kind ~ '^[A-Z][A-Z0-9_]{1,31}$'),
    CONSTRAINT media_variant_format_values CHECK (format IN ('webp', 'avif', 'jpeg', 'png')),
    CONSTRAINT media_variant_dims_positive CHECK (width > 0 AND height > 0),
    CONSTRAINT media_variant_size_positive CHECK (size_bytes > 0),
    CONSTRAINT media_variant_kind_uq       UNIQUE (asset_id, kind),
    CONSTRAINT media_variant_key_uq        UNIQUE (key)
);

COMMENT ON TABLE media_variant IS 'Processed renditions, public and immutable. Deleting an asset deletes its variants (and the service deletes the objects with S3 DeleteObjects).';
