#!/usr/bin/env python3
"""Writes infra/loadtest/envoy.generated.yaml: the gateway's envoy.yaml with every rate-limit token bucket multiplied.

The shipped limits (600 requests per minute per client IP before authentication, 300 per user after it, 30 uploads, 60 searches ...)
are right for production and wrong for a load test: every request of a test comes from one IP, so the test would measure the rate
limiter and nothing else. The limiter stays in the path (so its cost is measured), only its numbers grow.

  python3 scripts/loadtest-gateway.py [--factor 100] [--check]     make up-load calls it; the output is not committed
"""
import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "services" / "gateway" / "envoy" / "envoy.yaml"
OUT = ROOT / "infra" / "loadtest" / "envoy.generated.yaml"
BUCKET = re.compile(r"(\b(?:max_tokens|tokens_per_fill):\s*)(\d+)")


def build(factor):
    text = SRC.read_text(encoding="utf-8")
    n = len(BUCKET.findall(text))
    out = BUCKET.sub(lambda m: f"{m.group(1)}{int(m.group(2)) * factor}", text)
    header = (f"# GENERATED by scripts/loadtest-gateway.py from services/gateway/envoy/envoy.yaml - do not edit, do not use outside a load test.\n"
              f"# Every rate-limit token bucket ({n // 2} buckets) multiplied by {factor}.\n")
    return header + out, n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--factor", type=int, default=100)
    ap.add_argument("--check", action="store_true", help="only verify that the transformation works on the current envoy.yaml (CI)")
    args = ap.parse_args()
    if args.factor < 1:
        sys.exit("--factor must be at least 1")
    text, n = build(args.factor)
    doc = yaml.safe_load(text)  # still valid YAML, still an Envoy bootstrap
    if "static_resources" not in doc or n == 0 or n % 2:
        sys.exit(f"unexpected envoy.yaml: {n} token bucket numbers found (max_tokens and tokens_per_fill come in pairs)")
    before = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    if sorted(before) != sorted(doc):
        sys.exit("the transformation changed the structure of envoy.yaml")
    if args.check:
        print(f"ok: {n // 2} token buckets can be multiplied")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {n // 2} rate-limit buckets x{args.factor}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
