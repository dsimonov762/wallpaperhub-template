#!/usr/bin/env python3
"""Writes infra/https/envoy.generated.yaml: the gateway's envoy.yaml plus a TLS listener (make up-https).

The shipped envoy.yaml stays plain HTTP (it must start without certificates). From it this script derives the file the https overlay mounts:

  * a second listener `public_tls` on :8443 with the same filter chain as `public` (routes, JWT check, rate limits, CORS, ...), terminating TLS with
    the mkcert certificate from infra/certs: TLS 1.2 or newer, HTTP/2 and HTTP/1.1 (ALPN). README section 3.1: TLS terminates at the gateway.
  * HSTS neutralised (max-age=0) in the whole file. Reason: a browser applies HSTS to the host name and ALL its ports, so one visit to
    https://localhost:8443 with `max-age=31536000; includeSubDomains` would make it refuse http://localhost:8180, :3000, :8080 ... for a year
    (in Chrome: chrome://net-internals/#hsts to undo it). max-age=0 also removes any HSTS state an earlier visit left behind.
  * CORS: the https twins of the allowed localhost origins, and https://<name>.wallpaperhub.localhost[:port].
  * with --issuer URL: the JWT issuer the gateway accepts (Keycloak served over https, make up-https HTTPS_ISSUER=1).

  python3 scripts/https-gateway.py [--keycloak-https | --issuer https://localhost:8543/realms/wallpaperhub] [--check]
"""
import argparse
import copy
import os
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "services" / "gateway" / "envoy" / "envoy.yaml"
OUT = ROOT / "infra" / "https" / "envoy.generated.yaml"
HSTS = "max-age=31536000; includeSubDomains"
ISSUER = "http://localhost:8180/realms/wallpaperhub"
TLS_PORT = 8443
CERT_DIR = "/etc/envoy/certs"


def dotenv_port(name, default):
    """PORT_* from the environment or infra/.env (the same variables docker-compose.yml reads)."""
    if os.environ.get(name):
        return os.environ[name]
    f = ROOT / "infra" / ".env"
    if f.is_file():
        m = re.search(rf"^\s*{name}=(\S+)", f.read_text(encoding="utf-8"), re.M)
        if m:
            return m.group(1).strip("\"'")
    return default


def build(issuer=None):
    text = SRC.read_text(encoding="utf-8")
    if text.count(HSTS) < 1:
        sys.exit("envoy.yaml has no HSTS header with the expected value: update scripts/https-gateway.py")
    text = text.replace(HSTS, "max-age=0")
    # CORS: https twins of the allowed localhost origins (a front end served over https calls the gateway over https)
    cors = re.compile(r'^(?P<ind>\s*)- \{ exact: "http://localhost:8080" \}\n', re.M)
    if not cors.search(text):
        sys.exit("envoy.yaml: the CORS origin list changed: update scripts/https-gateway.py")
    extra = ('{ind}- {{ exact: "https://localhost:5173" }}\n{ind}- {{ exact: "https://localhost:4200" }}\n{ind}- {{ exact: "https://localhost:{p}" }}\n'
             '{ind}- {{ safe_regex: {{ regex: "https://[a-z0-9-]+\\\\.wallpaperhub\\\\.localhost(:[0-9]+)?" }} }}\n')
    text = cors.sub(lambda m: m.group(0) + extra.format(ind=m.group("ind"), p=TLS_PORT), text)
    if issuer:
        if text.count(f"issuer: {ISSUER}") != 1:
            sys.exit("envoy.yaml: the JWT issuer line changed: update scripts/https-gateway.py")
        text = text.replace(f"issuer: {ISSUER}", f"issuer: {issuer}")
    doc = yaml.safe_load(text)
    listeners = doc["static_resources"]["listeners"]
    idx, pub = next((i, l) for i, l in enumerate(listeners) if l["name"] == "public")
    tls = copy.deepcopy(pub)
    tls["name"] = "public_tls"
    tls["address"]["socket_address"]["port_value"] = TLS_PORT
    for chain in tls["filter_chains"]:
        chain["transport_socket"] = {
            "name": "envoy.transport_sockets.tls",
            "typed_config": {
                "@type": "type.googleapis.com/envoy.extensions.transport_sockets.tls.v3.DownstreamTlsContext",
                "common_tls_context": {
                    "tls_params": {"tls_minimum_protocol_version": "TLSv1_2"},
                    "alpn_protocols": ["h2", "http/1.1"],
                    "tls_certificates": [{
                        "certificate_chain": {"filename": f"{CERT_DIR}/wallpaperhub.pem"},
                        "private_key": {"filename": f"{CERT_DIR}/wallpaperhub-key.pem"},
                    }],
                },
            },
        }
    listeners.insert(idx + 1, tls)
    header = ("# GENERATED by scripts/https-gateway.py from services/gateway/envoy/envoy.yaml - do not edit, do not use outside local development.\n"
              f"# Adds the TLS listener :{TLS_PORT}, sets HSTS to max-age=0 (see the script), allows https origins in CORS"
              + (f", accepts tokens issued by {issuer}" if issuer else "") + ".\n")
    return header + yaml.safe_dump(doc, sort_keys=False, width=140, default_flow_style=False), doc


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--issuer", help="URL of the Keycloak realm as the browser sees it, when Keycloak is served over https")
    ap.add_argument("--keycloak-https", action="store_true", help="shortcut: --issuer https://localhost:$PORT_KEYCLOAK_TLS(8543)/realms/wallpaperhub")
    ap.add_argument("--check", action="store_true", help="only verify that the transformation works on the current envoy.yaml (CI)")
    args = ap.parse_args()
    issuer = args.issuer or (f"https://localhost:{dotenv_port('PORT_KEYCLOAK_TLS', '8543')}/realms/wallpaperhub" if args.keycloak_https else None)
    args.issuer = issuer
    out, doc = build(issuer)
    names = [l["name"] for l in doc["static_resources"]["listeners"]]
    if names.count("public_tls") != 1 or "public" not in names:
        sys.exit(f"unexpected listeners: {names}")
    if args.check:
        print(f"ok: TLS listener can be derived (listeners: {', '.join(names)})")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: listeners {', '.join(names)}" + (f"; issuer {args.issuer}" if args.issuer else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
