#!/usr/bin/env python3
"""Architecture decision records (docs/adr/). Standard library only.

  adr.py check                          every record is well formed, links resolve, supersessions agree both ways, the index is current
  adr.py index                          rewrite the table in docs/adr/README.md from the records
  adr.py new "Title" [--supersedes N]   next number from docs/adr/template.md; --supersedes also marks record N as superseded

make adr-check | adr-index | adr-new T="Title" [SUPERSEDES=0007].  What a record is and when to write one: docs/adr/README.md
ADR_DIR=<dir> works on another directory (the tests of this script do).
"""
import argparse
import datetime
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADR_DIR = os.path.abspath(os.environ.get("ADR_DIR") or os.path.join(ROOT, "docs", "adr"))

STATUSES = ("Proposed", "Accepted", "Rejected", "Deprecated", "Superseded")
REQUIRED = ("Context", "Decision", "Consequences")
FILE_RE = re.compile(r"^(\d{4})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
H1_RE = re.compile(r"^# (\d{4})\. (\S.*)$")
META_RE = re.compile(r"^- ([A-Za-z ]+): (.*)$")
REF_RE = re.compile(r"\[(\d{4})\]\(([^)\s]+)\)")
LINK_RE = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
FENCE_RE = re.compile(r"^\s*(```|~~~)")
START, END = "<!-- adr-index:start (generated by scripts/adr.py, do not edit) -->", "<!-- adr-index:end -->"


def slug(heading):
    """GitHub's anchor for a heading (enough of it for the headings of this repository)."""
    h = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    h = h.replace("`", "").replace("*", "")
    h = h.strip().lower()
    h = re.sub(r"[^\w\- ]", "", h, flags=re.UNICODE)
    return h.replace(" ", "-")


def md_lines_outside_code(text):
    """(line number, line) without fenced code blocks."""
    fenced = False
    for n, line in enumerate(text.splitlines(), 1):
        if FENCE_RE.match(line):
            fenced = not fenced
            continue
        if not fenced:
            yield n, line


def anchors_of(path, cache={}):
    if path not in cache:
        found, seen = set(), {}
        with open(path, encoding="utf-8") as f:
            for _, line in md_lines_outside_code(f.read()):
                m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
                if m:
                    s = slug(m.group(1))
                    k = seen.get(s, 0)
                    seen[s] = k + 1
                    found.add(s if k == 0 else f"{s}-{k}")
        cache[path] = found
    return cache[path]


class Record:
    def __init__(self, path):
        self.path = path
        self.name = os.path.basename(path)
        self.errors = []
        m = FILE_RE.match(self.name)
        self.number = int(m.group(1)) if m else None
        self.title = ""
        self.meta = {}
        self.sections = {}
        with open(path, encoding="utf-8") as f:
            self.text = f.read()
        self._parse()

    def err(self, msg, line=None):
        self.errors.append(f"{os.path.relpath(self.path, ROOT)}{f':{line}' if line else ''}: {msg}")

    def _parse(self):
        lines = self.text.splitlines()
        if not lines:
            return self.err("empty file")
        h = H1_RE.match(lines[0])
        if not h:
            self.err("the first line must be '# NNNN. Title'", 1)
        else:
            self.title = h.group(2).strip()
            if self.number is not None and int(h.group(1)) != self.number:
                self.err(f"the title says {h.group(1)}, the file name says {self.name[:4]}", 1)
        # metadata: '- Key: value' lines between the title and the first '##'
        section = None
        for n, line in enumerate(lines[1:], 2):
            if line.startswith("## "):
                section = line[3:].strip()
                self.sections.setdefault(section, [])
                continue
            if section is None:
                mm = META_RE.match(line)
                if mm:
                    key = mm.group(1).strip()
                    if key in self.meta:
                        self.err(f"'{key}' given twice", n)
                    self.meta[key] = mm.group(2).strip()
                elif line.strip():
                    self.err("only '- Key: value' lines are allowed between the title and the first section", n)
            else:
                self.sections[section].append(line)
        for key in self.meta:
            if key not in ("Status", "Date", "Supersedes", "Superseded by"):
                self.err(f"unknown field '{key}' (Status, Date, Supersedes, Superseded by)")
        status = self.meta.get("Status")
        if status is None:
            self.err("missing '- Status: ...'")
        elif status not in STATUSES:
            self.err(f"Status is '{status}', expected one of: {', '.join(STATUSES)}")
        date = self.meta.get("Date")
        if date is None:
            self.err("missing '- Date: YYYY-MM-DD'")
        else:
            try:
                datetime.date.fromisoformat(date)
            except ValueError:
                self.err(f"Date '{date}' is not a date like 2026-11-20")
        names = [s for s in self.sections]
        want = [r for r in REQUIRED]
        got = [s for s in names if s in REQUIRED]
        for r in REQUIRED:
            if r not in names:
                self.err(f"missing section '## {r}'")
            elif not self.body(r):
                self.err(f"section '## {r}' is empty (the comment of the template does not count)")
        if all(r in names for r in want) and got != want:
            self.err(f"sections must come in the order {', '.join(REQUIRED)}")

    def body(self, section):
        text = "\n".join(self.sections.get(section, []))
        return re.sub(r"<!--.*?-->", "", text, flags=re.S).strip()

    def refs(self, key):
        """[(number, target file name)] of a Supersedes / Superseded by field."""
        return [(int(n), t) for n, t in REF_RE.findall(self.meta.get(key, ""))]

    def check_links(self):
        in_code = False
        for n, raw in enumerate(self.text.splitlines(), 1):
            if FENCE_RE.match(raw):
                in_code = not in_code
                continue
            if in_code:
                continue
            line = re.sub(r"`[^`]*`", "", raw)                       # an example inside backticks is not a link
            for m in LINK_RE.finditer(line):
                target = m.group(1)
                if re.match(r"^[a-z][a-z0-9+.-]*:", target):          # https:, mailto: ... are not checked (no network)
                    continue
                file_part, _, anchor = target.partition("#")
                dest = self.path if file_part == "" else os.path.normpath(os.path.join(os.path.dirname(self.path), file_part))
                if not os.path.exists(dest):
                    self.err(f"link to '{target}': no such file", n)
                elif anchor and dest.endswith(".md") and anchor not in anchors_of(dest):
                    self.err(f"link to '{target}': {os.path.relpath(dest, ROOT)} has no heading with that anchor", n)


def load():
    if not os.path.isdir(ADR_DIR):
        sys.exit(f"{os.path.relpath(ADR_DIR, ROOT)} does not exist")
    records, problems = [], []
    for name in sorted(os.listdir(ADR_DIR)):
        if name in ("README.md", "template.md"):
            continue
        if not FILE_RE.match(name):
            problems.append(f"{os.path.relpath(os.path.join(ADR_DIR, name), ROOT)}: not a record (NNNN-short-title.md, lower case, hyphens)")
            continue
        records.append(Record(os.path.join(ADR_DIR, name)))
    return records, problems


def relationship_errors(records):
    by_no = {r.number: r for r in records}
    for r in records:
        sup_by, sup = r.refs("Superseded by"), r.refs("Supersedes")
        status = r.meta.get("Status")
        if status == "Superseded" and not sup_by:
            r.err("Status is Superseded, so it needs '- Superseded by: [NNNN](NNNN-title.md)'")
        if status != "Superseded" and "Superseded by" in r.meta:
            r.err("'Superseded by' is set, so Status must be Superseded")
        for key, pairs in (("Supersedes", sup), ("Superseded by", sup_by)):
            if key in r.meta and not pairs:
                r.err(f"'{key}' has no link like [0007](0007-title.md)")
            for n, target in pairs:
                other = by_no.get(n)
                if other is None:
                    r.err(f"'{key}' names {n:04d}, which does not exist")
                    continue
                if os.path.basename(target) != other.name:
                    r.err(f"'{key}': the link text says {n:04d} but the link goes to {target}")
                if n == r.number:
                    r.err(f"'{key}' names the record itself")
                if key == "Supersedes":
                    if n > r.number:
                        r.err(f"supersedes {n:04d}, a later record")
                    if r.number not in [x for x, _ in other.refs("Superseded by")]:
                        r.err(f"supersedes {n:04d}, but {other.name} does not say 'Superseded by' this record")
                else:
                    if n < r.number:
                        r.err(f"superseded by {n:04d}, an earlier record")
                    if r.number not in [x for x, _ in other.refs("Supersedes")]:
                        r.err(f"superseded by {n:04d}, but {other.name} does not say 'Supersedes' this record")


def index_block(records):
    rows = ["| # | Decision | Status | Date |", "|---|---|---|---|"]
    for r in records:
        status = r.meta.get("Status", "?")
        if status == "Superseded":
            status = "Superseded by " + ", ".join(f"[{n:04d}]({t})" for n, t in r.refs("Superseded by"))
        rows.append(f"| [{r.number:04d}]({r.name}) | {r.title} | {status} | {r.meta.get('Date', '?')} |")
    return "\n".join([START, "", *rows, "", END])


def read_index():
    path = os.path.join(ADR_DIR, "README.md")
    if not os.path.exists(path):
        return path, None
    with open(path, encoding="utf-8") as f:
        return path, f.read()


def numbering_problems(records):
    nums = [r.number for r in records]
    out = []
    if len(set(nums)) != len(nums):
        out.append("numbering: two records have the same number")
    for i, n in enumerate(nums, 1):
        if n != i:
            out.append(f"numbering: expected {i:04d} after {i - 1:04d}, found {n:04d} (numbers start at 0001 and have no gaps or repeats)")
            break
    return out


def cmd_check(_):
    records, problems = load()
    problems.extend(numbering_problems(records))
    relationship_errors(records)
    for r in records:
        r.check_links()
        problems.extend(r.errors)
    template = os.path.join(ADR_DIR, "template.md")
    if not os.path.exists(template):
        problems.append("docs/adr/template.md is missing")
    else:
        t = open(template, encoding="utf-8").read()
        for ph in ("{{NUMBER}}", "{{TITLE}}", "{{DATE}}"):
            if ph not in t:
                problems.append(f"docs/adr/template.md has no {ph}")
        for s in REQUIRED:
            if f"## {s}" not in t:
                problems.append(f"docs/adr/template.md has no '## {s}'")
    path, text = read_index()
    if text is None or START not in text or END not in text:
        problems.append(f"{os.path.relpath(path, ROOT)} needs the two markers around the table: {START} ... {END}")
    elif not problems:
        current = text[text.index(START): text.index(END) + len(END)]
        if current != index_block(records):
            problems.append("the index in docs/adr/README.md is out of date: run  make adr-index")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print(f"\n{len(problems)} problem(s) in the architecture decision records", file=sys.stderr)
        return 1
    print(f"{len(records)} records, numbering, sections, links, supersessions and index are fine")
    return 0


def cmd_index(_):
    records, problems = load()
    if problems or any(r.errors for r in records):
        print("fix `make adr-check` first", file=sys.stderr)
        return 1
    path, text = read_index()
    if text is None or START not in text or END not in text:
        print(f"{os.path.relpath(path, ROOT)} needs the two markers around the table: {START} ... {END}", file=sys.stderr)
        return 1
    new = text[: text.index(START)] + index_block(records) + text[text.index(END) + len(END):]
    if new != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
        print(f"updated {os.path.relpath(path, ROOT)} ({len(records)} records)")
    else:
        print("index already current")
    return 0


def make_slug(title):
    s = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    if len(s) > 60:
        s = s[:60].rsplit("-", 1)[0]
    return s


def cmd_new(args):
    title = args.title.strip()
    slug_ = make_slug(title)
    if not slug_:
        print("the title needs letters or digits", file=sys.stderr)
        return 1
    records, problems = load()
    # a record that is still a template (empty sections) does not stop the next one; anything else wrong does
    problems += numbering_problems(records) + [e for r in records for e in r.errors if "is empty" not in e]
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print("fix these (make adr-check) before adding a record", file=sys.stderr)
        return 1
    number = max([r.number for r in records], default=0) + 1
    old = None
    if args.supersedes:
        n = int(args.supersedes)
        old = next((r for r in records if r.number == n), None)
        if old is None:
            print(f"--supersedes: there is no record {n:04d}", file=sys.stderr)
            return 1
        if old.meta.get("Status") == "Superseded":
            print(f"--supersedes: {old.name} is already superseded by {old.meta.get('Superseded by')}", file=sys.stderr)
            return 1
    template = os.path.join(ADR_DIR, "template.md")
    with open(template, encoding="utf-8") as f:
        text = f.read()
    name = f"{number:04d}-{slug_}.md"
    text = text.replace("{{NUMBER}}", f"{number:04d}").replace("{{TITLE}}", title).replace("{{DATE}}", datetime.date.today().isoformat())
    if old:
        text = re.sub(r"^(- Date: .*)$", rf"\1\n- Supersedes: [{old.number:04d}]({old.name})", text, count=1, flags=re.M)
    path = os.path.join(ADR_DIR, name)
    with open(path, "x", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if old:
        t = old.text
        t = re.sub(r"^- Status: .*$", "- Status: Superseded", t, count=1, flags=re.M)
        t = re.sub(r"^(- Status: Superseded)$", rf"\1\n- Superseded by: [{number:04d}]({name})", t, count=1, flags=re.M)
        # keep the field order Status, Date, Supersedes, Superseded by
        with open(old.path, "w", encoding="utf-8", newline="\n") as f:
            f.write(t)
    print(f"created {os.path.relpath(path, ROOT)}" + (f" and marked {old.name} as superseded" if old else ""))
    # the new record is still a template, so the index is built without running the full check
    records, _ = load()
    p, idx = read_index()
    if idx and START in idx and END in idx:
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(idx[: idx.index(START)] + index_block(records) + idx[idx.index(END) + len(END):])
    print("fill in Context, Decision and Consequences, set Status to Accepted when the decision is made, then: make adr-check")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    sub.add_parser("index").set_defaults(fn=cmd_index)
    p = sub.add_parser("new")
    p.add_argument("title")
    p.add_argument("--supersedes", metavar="N")
    p.set_defaults(fn=cmd_new)
    args = ap.parse_args()
    sys.exit(args.fn(args))


if __name__ == "__main__":
    main()
