#!/usr/bin/env bash
# Runs a k6 profile of loadtest/ against the local stack.   scripts/k6.sh PROFILE [extra k6 arguments]
#
#   PROFILE   smoke (default) | load | stress | spike | soak | uploads | ratelimit      what each does: docs/LOAD.md
#
# Settings are environment variables (make load-run RATE=20 DURATION=10m, or RATE=20 scripts/k6.sh load):
#   RATE (journeys/s)  DURATION  RAMP  STEP  MAX_RATE  SPIKE  THINK_TIME  SKIP (e.g. graphql)  WITH_UPLOADS  UPLOAD_POOL  UPLOAD_RATE  UPLOAD_MAX_VUS
#   BUDGET_SCALE  EXPECT_LIMIT  RATELIMIT_RECOVER  BASE_URL  KEYCLOAK_URL  ALLOW_REMOTE  K6 (path of a k6 binary)  K6_IMAGE  PROM_URL
# Metrics go to Prometheus (-> Grafana dashboard "Load test (k6)") when it answers on PORT_PROMETHEUS; K6_PROM=0 turns that off.
# Works in WSL, Git Bash and Linux/macOS: an installed k6, else the grafana/k6 container.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
PROFILE="${1:-smoke}"; [ $# -gt 0 ] && shift
case "$PROFILE" in smoke|load|stress|spike|soak|uploads|ratelimit) ;; *) echo "unknown profile '$PROFILE': smoke load stress spike soak uploads ratelimit" >&2; exit 2;; esac

# ports from infra/.env, like the other scripts
if [ -f infra/.env ]; then set -a; . infra/.env; set +a; fi
BASE_URL="${BASE_URL:-http://localhost:${PORT_GATEWAY:-8080}}"
KEYCLOAK_URL="${KEYCLOAK_URL:-http://localhost:${PORT_KEYCLOAK:-8180}}"
PROM_URL="${PROM_URL:-http://localhost:${PORT_PROMETHEUS:-9090}}"
K6_IMAGE="${K6_IMAGE:-grafana/k6:1.6.0}"

[ -f seed/out/manifest.json ] || { echo "seed/out/manifest.json is missing (the load test takes ids and users from the seed data): make seed-build, and make seed to load it into the stack" >&2; exit 1; }
if [ "$PROFILE" = uploads ] || [ "${WITH_UPLOADS:-0}" = 1 ]; then
  [ -f loadtest/.data/uploads/0000.png ] || { echo "no upload pictures: make load-data" >&2; exit 1; }
fi
if [ "$PROFILE" = ratelimit ] && grep -q "GENERATED by scripts/loadtest-gateway.py" infra/loadtest/envoy.generated.yaml 2>/dev/null \
   && docker inspect -f '{{range .Mounts}}{{.Source}} {{end}}' "$(docker compose -p wallpaperhub ps -q gateway 2>/dev/null | head -1)" 2>/dev/null | grep -q "envoy.generated.yaml"; then
  echo "the gateway runs with the raised limits (make up-load): the rate-limit profile tests the SHIPPED limits. Restart it with make up-apps (or make up-mocks)." >&2; exit 1
fi

mkdir -p loadtest/.run
RUN_ID="${PROFILE}-$(date +%m%d-%H%M%S)"
ENVS=()
for v in RATE DURATION RAMP STEP MAX_RATE SPIKE THINK_TIME SKIP WITH_UPLOADS UPLOAD_POOL UPLOAD_RATE UPLOAD_MAX_VUS UPLOAD_READY_P95 UPLOAD_READY_TIMEOUT \
         BUDGET_SCALE EXPECT_LIMIT RATELIMIT_RECOVER ALLOW_REMOTE REALM CLIENT_ID PASSWORD SMOKE_ITERATIONS; do
  [ -n "${!v:-}" ] && ENVS+=(-e "$v=${!v}")
done

OUT=()
PROM_ON=0
if [ "${K6_PROM:-1}" != 0 ] && curl -sf -m 2 "$PROM_URL/-/ready" >/dev/null 2>&1; then
  PROM_ON=1
  OUT=(--out experimental-prometheus-rw --tag "testid=$RUN_ID")
fi

if [ -n "${K6:-}" ]; then CMD=("$K6"); NATIVE=1
elif command -v k6 >/dev/null 2>&1; then CMD=(k6); NATIVE=1
elif command -v docker >/dev/null 2>&1; then
  NATIVE=0
  echo "k6 not found, using the container $K6_IMAGE (install k6 for less overhead: winget install k6)"
  # inside the container localhost is the container: reach the host through Docker Desktop's alias
  BASE_URL="${BASE_URL//localhost/host.docker.internal}"; KEYCLOAK_URL="${KEYCLOAK_URL//localhost/host.docker.internal}"; PROM_URL="${PROM_URL//localhost/host.docker.internal}"
  CMD=(docker run --rm -i --add-host=host.docker.internal:host-gateway -v "$ROOT:/repo" -w /repo
       -e K6_PROMETHEUS_RW_SERVER_URL="$PROM_URL/api/v1/write" -e K6_PROMETHEUS_RW_TREND_STATS -e K6_PROMETHEUS_RW_PUSH_INTERVAL "$K6_IMAGE")
else echo "need k6 (https://k6.io) or docker" >&2; exit 2; fi

export K6_PROMETHEUS_RW_TREND_STATS="${K6_PROMETHEUS_RW_TREND_STATS:-p(95),p(99),avg,max,min,med}" K6_PROMETHEUS_RW_PUSH_INTERVAL="${K6_PROMETHEUS_RW_PUSH_INTERVAL:-5s}"
[ "$NATIVE" = 1 ] && export K6_PROMETHEUS_RW_SERVER_URL="$PROM_URL/api/v1/write"

echo "k6 profile '$PROFILE' -> $BASE_URL   run id: $RUN_ID"
[ "$PROM_ON" = 1 ] && echo "metrics -> Prometheus; Grafana: dashboard 'Load test (k6)', run '$RUN_ID'" || echo "Prometheus not reachable on $PROM_URL: no dashboard (make up-obs), the summary below is all there is"

set +e
"${CMD[@]}" run "${OUT[@]}" --summary-export "loadtest/.run/summary-$RUN_ID.json" -e "PROFILE=$PROFILE" -e "BASE_URL=$BASE_URL" -e "KEYCLOAK_URL=$KEYCLOAK_URL" \
  ${ENVS[@]+"${ENVS[@]}"} "$@" loadtest/main.js
rc=$?
set -e
case $rc in
  0)  echo "k6: all thresholds met" ;;
  99) echo "k6: a threshold failed (above, the lines marked with a cross). summary: loadtest/.run/summary-$RUN_ID.json" ;;
  *)  echo "k6: the test could not run (exit $rc)" ;;
esac
exit $rc
