#!/usr/bin/env python3
"""Failure injection with Toxiproxy: break the connections between the services and what they depend on, and check what happens.

  chaos.py status                         proxies, whether enabled, active toxics
  chaos.py down|up GLOB...                refuse connections / accept again        chaos.py down 'catalog-*'   chaos.py down '*-redis'
  chaos.py latency GLOB MS [--jitter MS]  delay every response
  chaos.py timeout GLOB [--ms N]          accept the connection, then swallow the traffic (N ms, 0 = forever): "hangs"
  chaos.py reset-peer GLOB                connection reset by peer (TCP RST)
  chaos.py bandwidth GLOB KBPS            limit throughput
  chaos.py limit-data GLOB BYTES          cut the connection after N bytes
  chaos.py slow-close GLOB MS             delay the closing of connections
  chaos.py reset                          remove every toxic, enable every proxy, resume paused containers
  chaos.py edges                          the proxies defined in infra/chaos/edges.yaml
  chaos.py env SERVICE [--host H]         the environment variables to put a service run from the IDE behind its proxies
  chaos.py list                           the scenarios in infra/chaos/scenarios
  chaos.py run SCENARIO|all [--keep]      baseline probes, inject, probe again, remove, wait for recovery, report
  chaos.py gen [--check]                  edges.yaml -> infra/chaos/toxiproxy.json + infra/docker-compose.chaos.yml

GLOB matches proxy names (<service>-<dependency>, e.g. catalog-elasticsearch): fnmatch rules, several allowed.
Environment: TOXIPROXY_URL (default http://localhost:<PORT_TOXIPROXY or 8474>), CHAOS_BASE_URL (gateway), KEYCLOAK_URL.
Standard library only, except PyYAML for everything that reads edges.yaml or scenarios (make chaos-* use the repo's venv).
"""
