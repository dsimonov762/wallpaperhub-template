    if args.cmd == "gen":
        return cmd_gen(args)
    if args.cmd == "edges":
        return cmd_edges(args)
    if args.cmd == "env":
        return cmd_env(args)
    if args.cmd == "list":
        return cmd_list(args)
    api = Api()
    if args.cmd == "status":
        return cmd_status(api, args)
    if args.cmd == "reset":
        api.reset()
