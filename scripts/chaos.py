ROOT = Path(__file__).resolve().parent.parent
CHAOS = ROOT / "infra" / "chaos"
EDGES = CHAOS / "edges.yaml"
SCENARIOS = CHAOS / "scenarios"
PROXIES_JSON = CHAOS / "toxiproxy.json"
OVERLAY = ROOT / "infra" / "docker-compose.chaos.yml"
BASE_COMPOSE = ROOT / "infra" / "docker-compose.yml"
MANIFEST = ROOT / "seed" / "out" / "manifest.json"
PROXY_HOST = "toxiproxy"
PORT_RANGE = (15000, 15099)
PROJECT = "wallpaperhub"
FAULTS = ("down", "latency", "timeout", "reset-peer", "bandwidth", "limit-data", "slow-close")


def die(msg, code=2):
    print(msg, file=sys.stderr)
    sys.exit(code)


def yaml_load(path):
    try:
        import yaml
    except ImportError:
        die("PyYAML is needed here: make chaos-... does it for you, or: python3 -m pip install pyyaml")
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))


def dotenv():
    out = {}
    f = ROOT / "infra" / ".env"
    if f.is_file():
        for line in f.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\s*([A-Z0-9_]+)=(.*)", line)
            if m:
                out[m.group(1)] = m.group(2).strip().strip("\"'")
    return out


ENV = {**dotenv(), **os.environ}


# ---- edges -> generated files ------------------------------------------------------------------------------------------
def load_edges():
    data = yaml_load(EDGES)
    edges = []
    for svc, deps in data["services"].items():
        for dep, e in deps.items():
            edges.append({"name": f"{svc}-{dep}", "service": svc, "dep": dep, "port": e["port"], "upstream": e["upstream"], "env": e["env"]})
    return edges


def expand(template, port, host=PROXY_HOST):
    return template.replace("{host}", host).replace("{port}", str(port))


def generate(edges):
    proxies = [{"name": e["name"], "listen": f"0.0.0.0:{e['port']}", "upstream": e["upstream"], "enabled": True} for e in edges]
    lines = [
        "# GENERATED by scripts/chaos.py gen from infra/chaos/edges.yaml - do not edit; run: make chaos-gen",
        "#",
        "# Overlay for infra/docker-compose.yml (make up-chaos): Toxiproxy, and every service's connections to its dependencies",
        "# pointed at it. Without this file the stack is unchanged.",
        "services:",
        "  toxiproxy:",
        "    image: ${TOXIPROXY_IMAGE:-ghcr.io/shopify/toxiproxy:2.13.0}",
        "    restart: unless-stopped",
        "    mem_limit: 64m",
        '    command: ["-host=0.0.0.0", "-config=/config/toxiproxy.json"]',
        "    volumes:",
        "      - ./chaos/toxiproxy.json:/config/toxiproxy.json:ro",
        "    ports:",
        '      - "${BIND_ADDRESS:-127.0.0.1}:${PORT_TOXIPROXY:-8474}:8474"',
        f'      - "${{BIND_ADDRESS:-127.0.0.1}}:{PORT_RANGE[0]}-{PORT_RANGE[1]}:{PORT_RANGE[0]}-{PORT_RANGE[1]}"',
    ]
    by_service = {}
    for e in edges:
        by_service.setdefault(e["service"], []).append(e)
    for svc, es in by_service.items():
        lines += [f"  {svc}:", "    depends_on:", "      toxiproxy: { condition: service_started }", "    environment:"]
        for e in es:
            lines.append(f"      # {e['name']}  ->  {e['upstream']}")
            for key, tpl in e["env"].items():
                lines.append(f"      {key}: {json.dumps(expand(tpl, e['port']))}")
    return json.dumps(proxies, indent=2) + "\n", "\n".join(lines) + "\n"


def validate(edges):
    problems = []
    names, ports = set(), set()
    compose = yaml_load(BASE_COMPOSE)
    services = compose["services"]
    known_hosts = set(services)
    for s in services.values():
        for net in (s.get("networks") or {}).values() if isinstance(s.get("networks"), dict) else []:
            known_hosts |= set((net or {}).get("aliases", []))
    for e in edges:
        n = e["name"]
        if n in names:
            problems.append(f"{n}: defined twice")
        names.add(n)
        if e["port"] in ports:
            problems.append(f"{n}: port {e['port']} used twice")
        ports.add(e["port"])
        if not PORT_RANGE[0] <= e["port"] <= PORT_RANGE[1]:
            problems.append(f"{n}: port {e['port']} outside {PORT_RANGE[0]}-{PORT_RANGE[1]} (the published range)")
        host, _, port = e["upstream"].partition(":")
        if host not in known_hosts:
            problems.append(f"{n}: upstream host '{host}' is not a service of docker-compose.yml")
        svc = services.get(e["service"])
        if svc is None:
            problems.append(f"{n}: no service '{e['service']}' in docker-compose.yml")
            continue
        base_env = svc.get("environment") or {}
        seen = set()
        for key, tpl in e["env"].items():
            if key not in base_env:
                problems.append(f"{n}: {e['service']} has no environment variable {key} in docker-compose.yml")
                continue
            if (e["service"], key) in seen:
                problems.append(f"{n}: {key} set twice")
            base = str(base_env[key])
            if key.endswith("_PORT"):
                if base != port:
                    problems.append(f"{n}: {key} is {base} in docker-compose.yml, the upstream says {port}")
            elif host not in base:
                problems.append(f"{n}: {key}={base} does not mention the upstream host '{host}'")
            elif ":" in base.split(host, 1)[1][:1] and port and not re.match(rf":{port}\b", base.split(host, 1)[1]):
                problems.append(f"{n}: {key}={base} has another port than the upstream {port}")
        for e2 in edges:
            if e2 is not e and e2["service"] == e["service"]:
                clash = set(e["env"]) & set(e2["env"])
                if clash:
                    problems.append(f"{n} and {e2['name']} both set {sorted(clash)}")
    return sorted(set(problems))


KNOWN_VARS = {"rand", "wallpaper_id", "wallpaper_word", "collection_id", "sample_image"}
PROBE_KEYS = {"name", "request", "as", "body", "file", "fields", "headers", "expect", "expect_during", "max_ms", "max_ms_during", "recover_within", "timeout"}
FAULT_KEYS = {"edge", "fault", "stream", "ms", "jitter", "kbps", "bytes", "docker", "service"}
SCENARIO_KEYS = {"title", "readme", "faults", "probes", "settle", "repeat", "watch"}


def validate_scenarios(edges):
    problems = []
    names = [e["name"] for e in edges]
    compose = set(yaml_load(BASE_COMPOSE)["services"])
    files = sorted(SCENARIOS.glob("*.yaml"))
    if not files:
        problems.append("no scenarios in infra/chaos/scenarios")
    for f in files:
        w = f"scenario {f.stem}"
        sc = yaml_load(f)
        for k in sc:
            if k not in SCENARIO_KEYS:
                problems.append(f"{w}: unknown key '{k}'")
        for k in ("title", "faults", "probes"):
            if not sc.get(k):
                problems.append(f"{w}: '{k}' missing or empty")
        for fl in sc.get("faults") or []:
            for k in fl:
                if k not in FAULT_KEYS:
                    problems.append(f"{w}: unknown fault key '{k}'")
            if "docker" in fl:
                if fl["docker"] != "pause" or fl.get("service") not in compose:
                    problems.append(f"{w}: docker fault needs 'docker: pause' and a service of docker-compose.yml, got {fl}")
                continue
            kind = fl.get("fault")
            if kind not in FAULTS:
                problems.append(f"{w}: fault '{kind}' is not one of {', '.join(FAULTS)}")
                continue
            if not any(fnmatch.fnmatchcase(n, fl.get("edge", "")) for n in names):
                problems.append(f"{w}: edge '{fl.get('edge')}' matches no proxy of edges.yaml")
            if kind != "down":
                needs = {"latency": "ms", "bandwidth": "kbps", "limit-data": "bytes", "slow-close": "ms"}.get(kind)
                if needs and needs not in fl:
                    problems.append(f"{w}: fault '{kind}' needs '{needs}'")
        for p in sc.get("probes") or []:
            pw = f"{w}: probe '{p.get('name')}'"
            for k in p:
                if k not in PROBE_KEYS:
                    problems.append(f"{pw}: unknown key '{k}'")
            if not re.fullmatch(r"(GET|POST|PUT|PATCH|DELETE) /api/v1/\S*", p.get("request", "")):
                problems.append(f"{pw}: request should be 'METHOD /api/v1/...'")
            if not p.get("expect"):
                problems.append(f"{pw}: expect (a list of status codes) missing")
            text = json.dumps(p)
            for v in set(re.findall(r"\{(\w+)\}", text)):
                if v not in KNOWN_VARS and not re.fullmatch(r"\w+_(id|avatar)", v):
                    problems.append(f"{pw}: unknown variable {{{v}}}")
    return problems


def cmd_gen(args):
    edges = load_edges()
    problems = validate(edges) + validate_scenarios(edges)
    if problems:
        print("infra/chaos has problems:", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    proxies, overlay = generate(edges)
    if args.check:
        stale = [f.name for f, text in ((PROXIES_JSON, proxies), (OVERLAY, overlay)) if not f.is_file() or f.read_text(encoding="utf-8") != text]
        if stale:
            print(f"out of date: {', '.join(stale)}  (run: make chaos-gen)", file=sys.stderr)
            return 1
        print(f"chaos config is up to date ({len(edges)} proxies)")
        return 0
    PROXIES_JSON.write_text(proxies, encoding="utf-8", newline="\n")
    OVERLAY.write_text(overlay, encoding="utf-8", newline="\n")
    print(f"wrote {PROXIES_JSON.relative_to(ROOT)} and {OVERLAY.relative_to(ROOT)} ({len(edges)} proxies)")
    return 0


def cmd_edges(args):
    for e in load_edges():
        print(f"  {e['name']:<26} :{e['port']}  ->  {e['upstream']:<24} sets {', '.join(e['env'])}")
    return 0


def cmd_env(args):
    mine = [e for e in load_edges() if e["service"] == args.service]
    if not mine:
        die(f"no proxies for '{args.service}'; services: {sorted({e['service'] for e in load_edges()})}")
    print(f"# {args.service} behind Toxiproxy ({args.host}); the ports are published by make up-chaos")
    for e in mine:
        print(f"# {e['name']} -> {e['upstream']}")
        for key, tpl in e["env"].items():
            value = re.sub(r"\$\{(\w+):-([^}]*)\}", lambda m: ENV.get(m.group(1), m.group(2)), expand(tpl, e["port"], args.host))
            print(f"{key}={value}")
    return 0


# ---- Toxiproxy API -----------------------------------------------------------------------------------------------------
class Api:
    def __init__(self):
        self.base = ENV.get("TOXIPROXY_URL") or f"http://localhost:{ENV.get('PORT_TOXIPROXY', '8474')}"

    def call(self, method, path, body=None, ok=(200, 201, 204)):
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(self.base + path, data=data, method=method, headers={"Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=10) as r:
                raw = r.read()
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as e:
            if e.code in ok:
                return None
            die(f"Toxiproxy {method} {path}: {e.code} {e.read().decode()[:200]}")
        except (urllib.error.URLError, OSError) as e:
            die(f"cannot reach Toxiproxy at {self.base} ({e}).\nIs the stack up with the chaos overlay?  make up-chaos")

    def proxies(self):
        return self.call("GET", "/proxies")

    def match(self, globs):
        names = sorted(self.proxies())
        chosen = sorted({n for g in globs for n in names if fnmatch.fnmatchcase(n, g)})
        if not chosen:
            die(f"no proxy matches {globs}. proxies: {', '.join(names)}")
        return chosen

    def set_enabled(self, name, enabled):
        self.call("POST", f"/proxies/{name}", {"enabled": enabled})

    def toxic(self, name, kind, stream, attrs):
        tname = f"chaos_{kind}_{stream}"
        self.call("DELETE", f"/proxies/{name}/toxics/{tname}", ok=(404,))
        self.call("POST", f"/proxies/{name}/toxics", {"name": tname, "type": kind, "stream": stream, "toxicity": 1.0, "attributes": attrs})

    def reset(self):
        self.call("POST", "/reset")


TOXICS = {  # fault -> (toxic type, default stream, attribute builder)
    "latency": ("latency", "downstream", lambda p: {"latency": int(p["ms"]), "jitter": int(p.get("jitter", 0))}),
    "timeout": ("timeout", "upstream", lambda p: {"timeout": int(p.get("ms", 0))}),
    "reset-peer": ("reset_peer", "downstream", lambda p: {"timeout": int(p.get("ms", 0))}),
    "bandwidth": ("bandwidth", "downstream", lambda p: {"rate": int(p["kbps"])}),
    "limit-data": ("limit_data", "downstream", lambda p: {"bytes": int(p["bytes"])}),
    "slow-close": ("slow_close", "downstream", lambda p: {"delay": int(p["ms"])}),
}


def apply_fault(api, glob, fault, params=None, stream=None):
    params = params or {}
    if fault not in FAULTS:
        die(f"unknown fault '{fault}'; one of {', '.join(FAULTS)}")
    names = api.match([glob] if isinstance(glob, str) else glob)
    for n in names:
        if fault == "down":
            api.set_enabled(n, False)
        else:
            kind, default_stream, build = TOXICS[fault]
            try:
                attrs = build(params)
            except KeyError as e:
                die(f"fault '{fault}' needs {e.args[0]}")
            api.toxic(n, kind, stream or default_stream, attrs)
    return names


def cmd_status(api, args):
    proxies = api.proxies()
    if not proxies:
        print("no proxies configured")
        return 0
    for name in sorted(proxies):
        p = proxies[name]
        tox = ", ".join(f"{t['type']}({t['stream']}, {', '.join(f'{k}={v}' for k, v in t['attributes'].items())})" for t in p.get("toxics", []))
        state = "ok  " if p["enabled"] and not tox else ("DOWN" if not p["enabled"] else "SLOW")
        print(f"  {state}  {name:<26} {p['listen']:<14} -> {p['upstream']:<24} {tox}")
    return 0


# ---- scenarios ---------------------------------------------------------------------------------------------------------
def docker_pause(service, pause):
    cmd = ["docker", "compose", "-p", PROJECT, "pause" if pause else "unpause", service]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        die(f"{' '.join(cmd)}: {e}")
    if r.returncode:
        die(f"{' '.join(cmd)}: {r.stderr.strip()[:200]}")


class Probes:
    def __init__(self):
        self.base = (ENV.get("CHAOS_BASE_URL") or f"http://localhost:{ENV.get('PORT_GATEWAY', '8080')}").rstrip("/")
        self.kc = (ENV.get("KEYCLOAK_URL") or f"http://localhost:{ENV.get('PORT_KEYCLOAK', '8180')}").rstrip("/")
        self.tokens = {}
        self.vars = {}
        if MANIFEST.is_file():
            m = json.loads(MANIFEST.read_text(encoding="utf-8"))
            for u in m["users"]:
                self.vars[f"{u['username']}_id"] = u["id"]
                self.vars[f"{u['username']}_avatar"] = u.get("avatarAssetId") or ""
            pub = [w for w in m["wallpapers"] if w["status"] == "PUBLISHED"]
            self.vars["wallpaper_id"] = pub[0]["id"] if pub else ""
            self.vars["wallpaper_word"] = re.sub(r"\W", "", pub[0]["title"].split()[0]) if pub else ""
            self.vars["collection_id"] = m["collections"][0]["id"] if m["collections"] else ""
            ready = [a for a in m["assets"] if a["purpose"] == "WALLPAPER" and a["status"] == "READY"]
            if ready:
                small = min(ready, key=lambda a: (a["size_bytes"], a["id"]))
                self.vars["sample_image"] = str(ROOT / "seed" / "s3" / "originals" / small["original_key"])

    def token(self, user):
        if user not in self.tokens:
            body = urllib.parse.urlencode({"grant_type": "password", "client_id": "e2e-tests", "username": user, "password": "password"}).encode()
            try:
                with urllib.request.urlopen(urllib.request.Request(f"{self.kc}/realms/wallpaperhub/protocol/openid-connect/token", data=body), timeout=15) as r:
                    self.tokens[user] = json.load(r)["access_token"]
            except (urllib.error.URLError, OSError, KeyError, ValueError) as e:
                die(f"no token for {user} from {self.kc}: {e}")
        return self.tokens[user]

    def fill(self, text):
        def sub(m):
            key = m.group(1)
            if key == "rand":
                return "c" + uuid.uuid4().hex[:8]
            if key not in self.vars:
                die(f"scenario uses {{{key}}} but it is unknown (run make seed-build for the seed ids); known: {sorted(self.vars)}")
            return self.vars[key]
        return re.sub(r"\{(\w+)\}", sub, text)

    def send(self, probe):
        method, _, path = probe["request"].partition(" ")
        headers = {"Accept": "application/json"}
        user = probe.get("as", "alice")
        if user != "none":
            headers["Authorization"] = "Bearer " + self.token(user)
        data = None
        if "file" in probe:  # multipart upload of the smallest seed image
            boundary = uuid.uuid4().hex
            image = Path(self.fill(probe["file"]))
            parts = []
            for k, v in (probe.get("fields") or {}).items():
                parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'.encode())
            ctype = mimetypes.guess_type(image.name)[0] or "image/jpeg"
            parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="{image.name}"\r\nContent-Type: {ctype}\r\n\r\n'.encode()
                         + image.read_bytes() + b"\r\n")
            data = b"".join(parts) + f"--{boundary}--\r\n".encode()
            headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
        elif "body" in probe:
            data = self.fill(json.dumps(probe["body"])).encode()
            headers["Content-Type"] = "application/json"
        for k, v in (probe.get("headers") or {}).items():
            headers[k] = self.fill(str(v))
        if method in ("POST", "PUT", "PATCH", "DELETE"):
            headers["Idempotency-Key"] = str(uuid.uuid4())
        req = urllib.request.Request(self.base + self.fill(path), data=data, method=method, headers=headers)
        t0 = time.time()
        try:
            with urllib.request.urlopen(req, timeout=probe.get("timeout", 30)) as r:
                r.read()
                status = r.status
        except urllib.error.HTTPError as e:
            e.read()
            status = e.code
        except (urllib.error.URLError, OSError):
            status = 0
        return status, int((time.time() - t0) * 1000)


def judge(status, ms, expect, max_ms):
    return status in expect and (max_ms is None or ms <= max_ms)


def cmd_list(args):
    for f in sorted(SCENARIOS.glob("*.yaml")):
        s = yaml_load(f)
        print(f"  {f.stem:<26} {s['title']}")
    return 0


def cmd_run(api, args):
    f = SCENARIOS / f"{args.scenario}.yaml"
    if not f.is_file():
        die(f"no scenario '{args.scenario}'. available: {', '.join(p.stem for p in sorted(SCENARIOS.glob('*.yaml')))}")
    sc = yaml_load(f)
    pr = Probes()
    failed = 0
    print(f"scenario {args.scenario}: {sc['title']}")
    print(f"  basis: {sc.get('readme', '-')}")
    names = api.proxies()
    if not names:
        die("Toxiproxy has no proxies configured")

    def probe_line(label, p, text, ok):
        print(f"    {'PASS' if ok else 'FAIL'}  {p['name']:<44} {text}")
        return 0 if ok else 1

    api.reset()
    if not args.no_baseline:
        print("  baseline (no fault)")
        broken = 0
        for p in sc["probes"]:
            st, ms = pr.send(p)
            broken += probe_line("before", p, f"{st} in {ms} ms (expected {p['expect']})", judge(st, ms, p["expect"], p.get("max_ms")))
        if broken:
            print("  The baseline already fails: fix that first, a fault cannot be judged on a broken system. Is the stack the real services (make up-chaos), seeded (make seed)?")
            return 1
    applied, paused = [], []
    try:
        print("  fault")
        for fl in sc["faults"]:
            if "docker" in fl:
                docker_pause(fl["service"], True)
                paused.append(fl["service"])
                print(f"    docker pause {fl['service']}")
            else:
                params = {k: v for k, v in fl.items() if k not in ("edge", "fault", "stream")}
                hit = apply_fault(api, fl["edge"], fl["fault"], params, fl.get("stream"))
                applied += hit
                print(f"    {fl['fault']:<10} {', '.join(hit)}  {params or ''}")
        time.sleep(sc.get("settle", 5))
        repeat = sc.get("repeat", 3)
        print(f"  during the fault ({repeat} rounds, every answer must fit)")
        during_fail = 0
        for p in sc["probes"]:
            expect = p.get("expect_during", p["expect"])
            limit = p.get("max_ms_during", p.get("max_ms"))
            seen = [pr.send(p) for _ in range(repeat)]
            ok = all(judge(st, ms, expect, limit) for st, ms in seen)
            text = f"{', '.join(str(st) for st, _ in seen)} (max {max(ms for _, ms in seen)} ms; expected {expect}" + (f" within {limit} ms" if limit else "") + ")"
            during_fail += probe_line("during", p, text, ok)
        failed += during_fail
        if during_fail:
            print("    (if the answers equal the baseline the fault changed nothing: the services must run through the proxies, `make up-chaos`; mocks do not use dependencies)")
    finally:
        if args.keep:
            print("  --keep: the fault stays; undo with: make chaos C=reset")
        else:
            api.reset()
            for s in paused:
                docker_pause(s, False)
    if not args.keep:
        print("  recovery (fault removed, probes repeated until they are normal again)")
        for p in sc["probes"]:
            deadline = time.time() + p.get("recover_within", 30)
            t0, st, ms = time.time(), 0, 0
            while True:
                st, ms = pr.send(p)
                if judge(st, ms, p["expect"], p.get("max_ms")) or time.time() > deadline:
                    break
                time.sleep(1)
            ok = judge(st, ms, p["expect"], p.get("max_ms"))
            failed += probe_line("after", p, f"{st} after {int(time.time() - t0)} s" if ok else f"still {st} after {p.get('recover_within', 30)} s", ok)
    for w in sc.get("watch", []):
        print(f"  watch: {w}")
    print("  RESULT: " + ("all expectations met" if not failed else f"{failed} expectation(s) NOT met"))
    return 1 if failed else 0


