#!/usr/bin/env python3
"""deploy/helm/values/{apps,mocks}/<name>.yaml: the Helm values of every service, generated from infra/docker-compose.yml.   docs/KUBERNETES.md

  k8s-gen.py            write the files
  k8s-gen.py --check    fail when a file is missing, stale or not generated, and when the pieces that must agree do not (CI and a git hook run it)

Why generated: compose is where the environment of each service is defined and tested (variables, ports, memory limit, the names of the
other services). The chart takes the same values, so the cluster runs what compose runs and the two cannot drift apart.
The generator also checks what has to hold for the local cluster: the names of the Services are the hosts of envoy.yaml, every host
named in a variable is a service that exists, and the kind configuration publishes the gateway where compose does.
"""
import argparse
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPOSE = os.path.join(ROOT, "infra", "docker-compose.yml")
ENVOY = os.path.join(ROOT, "services", "gateway", "envoy", "envoy.yaml")
KIND = os.path.join(ROOT, "deploy", "kind", "kind-config.yaml")
OUT = os.path.join(ROOT, "deploy", "helm", "values")

GATEWAY_NODE_PORT = 30080            # the NodePort of the gateway; deploy/kind/kind-config.yaml maps it to the host
CPU_REQUEST = "100m"                 # compose sets no CPU limit; a request keeps the scheduler honest on a small cluster
MEM_REQUEST_SHARE = 2                # memory request = limit / 2
MOUNTS = {"../contracts": "/contracts"}   # compose bind mounts the cluster supports: host path -> path inside the kind node (kind-config.yaml mounts the same)
SECRET_NAME = re.compile(r"(SECRET|PASSWORD|PASSWD|TOKEN|_KEY)$")
CREDENTIAL_URL = re.compile(r"://[^/@\s:]*:[^/@\s]*@")
HEADER = "# GENERATED by scripts/k8s-gen.py from infra/docker-compose.yml (service {svc}). Do not edit: change the compose file and run  make k8s-gen\n"


def die(msg):
    sys.exit(f"k8s-gen: {msg}")


def interpolate(value, where):
    """${VAR:-default} -> default; the cluster takes the development defaults of infra/.env.example, a real cluster overrides them with values."""
    if not isinstance(value, str):
        value = str(value) if not isinstance(value, bool) else str(value).lower()

    def sub(m):
        if m.group(2) is None:
            die(f"{where}: ${{{m.group(1)}}} has no default, so there is nothing to put in the values file")
        return m.group(2)

    return re.sub(r"\$\{([A-Za-z0-9_]+)(?::-([^}]*))?\}", sub, value)


def memory(limit, where):
    m = re.fullmatch(r"(\d+)([mg])", str(limit))
    if not m:
        die(f"{where}: mem_limit '{limit}' is not like 640m or 2g")
    n, unit = int(m.group(1)), m.group(2)
    mi = n * (1024 if unit == "g" else 1)
    return f"{mi}Mi", f"{max(mi // MEM_REQUEST_SHARE, 1)}Mi"


def load_compose():
    with open(COMPOSE, encoding="utf-8") as f:
        return yaml.safe_load(f)["services"]


def container_ports(svc):
    out = []
    for p in svc.get("ports", []):
        out.append(int(str(p).rsplit(":", 1)[-1].split("/")[0]))
    return out


def values_for(name, svc, mode):
    where = f"service {name}"
    image = svc.get("image", "")
    m = re.fullmatch(r"([^:]+):([^:]+)", image)
    if not m:
        die(f"{where}: image '{image}' is not repository:tag")
    limit, request = memory(svc.get("mem_limit", ""), where)
    env, secret = {}, {}
    for k, v in (svc.get("environment") or {}).items():
        v = interpolate(v, f"{where} {k}")
        (secret if SECRET_NAME.search(k) or CREDENTIAL_URL.search(v) else env)[k] = v
    doc = {}
    if mode == "mocks":
        aliases = svc.get("networks", {}).get("default", {}).get("aliases") or []
        if len(aliases) != 1:
            die(f"{where}: a mock needs exactly one network alias (the name of the service it stands for)")
        fullname = aliases[0]
    else:
        fullname = name
    doc["fullnameOverride"] = fullname
    doc["image"] = {"repository": m.group(1), "tag": m.group(2)}
    if 9090 in container_ports(svc):
        doc["ports"] = {"grpc": 9090}
    if fullname == "gateway":
        doc["service"] = {"type": "NodePort", "nodePort": GATEWAY_NODE_PORT}
    if env:
        doc["env"] = env
    if secret:
        doc["secretEnv"] = secret
    doc["resources"] = {"requests": {"cpu": CPU_REQUEST, "memory": request}, "limits": {"memory": limit}}
    volumes, mounts = [], []
    for vol in svc.get("volumes", []):
        src, dst, *opt = str(vol).split(":")
        if src not in MOUNTS or MOUNTS[src] != dst:
            die(f"{where}: bind mount '{vol}' is not one the cluster supports (known: {', '.join(f'{a}:{b}' for a, b in MOUNTS.items())}); "
                f"add it to MOUNTS here and to extraMounts of deploy/kind/kind-config.yaml")
        vname = os.path.basename(dst)
        volumes.append({"name": vname, "hostPath": {"path": dst, "type": "Directory"}})
        mounts.append({"name": vname, "mountPath": dst, "readOnly": "ro" in opt})
    if volumes:
        doc["extraVolumes"], doc["extraVolumeMounts"] = volumes, mounts
    return fullname, doc


def render(name, doc):
    return HEADER.format(svc=name) + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=200)


def wanted(services):
    """{relative path: text} of every values file, and {fullname: [environment values]} per mode for the checks."""
    files, fullnames, hosts = {}, {"apps": set(), "mocks": set()}, {"apps": [], "mocks": []}
    for name, svc in services.items():
        profiles = svc.get("profiles", [])
        if "apps" in profiles and str(svc.get("image", "")).startswith("wallpaperhub/") and "build" in svc and name != "host-proxy":
            mode = "apps"
        elif "mocks" in profiles and str(svc.get("image", "")) == "wallpaperhub/mock:local":
            mode = "mocks"
        else:
            continue
        fullname, doc = values_for(name, svc, mode)
        files[f"{mode}/{fullname}.yaml"] = render(name, doc)
        fullnames[mode].add(fullname)
        hosts[mode].extend((fullname, k, v) for k, v in {**doc.get("env", {}), **doc.get("secretEnv", {})}.items())
    return files, fullnames, hosts


def envoy_upstreams():
    """{cluster: host} of the plain clusters of envoy.yaml."""
    with open(ENVOY, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    out = {}
    for c in cfg["static_resources"]["clusters"]:
        try:
            sa = c["load_assignment"]["endpoints"][0]["lb_endpoints"][0]["endpoint"]["address"]["socket_address"]
        except (KeyError, IndexError, TypeError):
            continue
        out[c["name"]] = sa["address"]
    return out


def host_names(key, value):
    """Host names that an environment variable points at (URLs, host:port, *_HOST)."""
    found = set(re.findall(r"(?:^|://|@|,)([A-Za-z0-9][A-Za-z0-9.-]*):\d+", value))
    if key.endswith("_HOST"):
        found.add(value)
    if key.endswith("_ADDR") and ":" in value:
        found.add(value.rsplit(":", 1)[0])
    return found


def consistency(services, fullnames, hosts):
    problems = []
    domain = {"account", "media", "catalog", "notification"}
    for mode in ("apps", "mocks"):
        missing = domain - fullnames[mode]
        if missing:
            problems.append(f"{mode}: no values for {', '.join(sorted(missing))}")
        if "gateway" not in fullnames[mode] and mode == "apps":
            problems.append("apps: no values for the gateway")
    # 1. the gateway's upstreams are Services of the cluster
    for cluster, host in envoy_upstreams().items():
        if cluster in domain and host not in fullnames["apps"] | fullnames["mocks"]:
            problems.append(f"envoy.yaml sends {cluster} to host '{host}', which no values file names (fullnameOverride)")
    # 2. every host that a variable names is a service the cluster can reach: deployed by the chart, or a compose service/alias on the attached network
    reachable = set(services)
    for svc in services.values():
        reachable.update(svc.get("networks", {}).get("default", {}).get("aliases", []) if isinstance(svc.get("networks"), dict) else [])
    for mode in ("apps", "mocks"):
        for fullname, key, value in hosts[mode]:
            for h in host_names(key, value):
                if h not in reachable | fullnames[mode] and h not in ("localhost", "127.0.0.1"):
                    problems.append(f"{mode}/{fullname}: {key} points at host '{h}', which is neither a compose service nor a service of this chart")
    # 3. the kind configuration publishes the gateway where compose does, and mounts what the mocks read
    gw_ports = [p for p in (services.get("gateway", {}).get("ports") or []) if str(p).endswith(":8080")]
    gw_host_port = re.search(r":(\d+):8080$", interpolate(gw_ports[0], "gateway ports")) if gw_ports else None
    try:
        with open(KIND, encoding="utf-8") as f:
            kind = f.read()
    except FileNotFoundError:
        return problems + ["deploy/kind/kind-config.yaml is missing"]
    cfg = yaml.safe_load(kind)
    node = cfg["nodes"][0]
    maps = {(m["containerPort"], m["hostPort"]) for m in node.get("extraPortMappings", [])}
    want_host = int(gw_host_port.group(1)) if gw_host_port else None
    if (GATEWAY_NODE_PORT, want_host) not in maps:
        problems.append(f"kind-config.yaml must map containerPort {GATEWAY_NODE_PORT} to hostPort {want_host} (the gateway's NodePort, and PORT_GATEWAY of compose)")
    mounts = {m["containerPath"] for m in node.get("extraMounts", [])}
    for dst in MOUNTS.values():
        if dst not in mounts:
            problems.append(f"kind-config.yaml must mount the repository's {os.path.basename(dst)}/ at {dst} in the node (the mocks read it)")
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    services = load_compose()
    files, fullnames, hosts = wanted(services)
    problems = consistency(services, fullnames, hosts)
    if args.check:
        for rel, text in sorted(files.items()):
            path = os.path.join(OUT, rel)
            if not os.path.exists(path):
                problems.append(f"deploy/helm/values/{rel} is missing")
            elif open(path, encoding="utf-8").read() != text:
                problems.append(f"deploy/helm/values/{rel} is out of date")
        for mode in ("apps", "mocks"):
            d = os.path.join(OUT, mode)
            for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
                if f"{mode}/{name}" not in files:
                    problems.append(f"deploy/helm/values/{mode}/{name} is not generated from the compose file (remove it, or its service is gone)")
        if problems:
            print("\n".join(problems), file=sys.stderr)
            print("\nfix the compose file or the kind configuration, then:  make k8s-gen   and commit the result", file=sys.stderr)
            return 1
        print(f"{len(files)} values files are current, the cluster names agree with envoy.yaml and compose, kind publishes the gateway")
        return 0
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    for rel, text in files.items():
        path = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    for mode in ("apps", "mocks"):
        d = os.path.join(OUT, mode)
        for name in os.listdir(d) if os.path.isdir(d) else []:
            if f"{mode}/{name}" not in files:
                os.remove(os.path.join(d, name))
    print(f"wrote {len(files)} files to deploy/helm/values/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
